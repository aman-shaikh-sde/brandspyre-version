import { Request, Response } from "express";
import {
  MetaIntegration,
  MetaCampaign,
  MetaLeadForm,
  MetaLeadSyncLog,
  MetaAdAccount,
} from "../../../db/ModelSceham/metaIntegrationSchema";
import { Lead } from "../../../db/ModelSceham/project/campagin";
import MetaService from "../../../services/metaService";
import mongoose from "mongoose";

/**
 * Get Meta Marketing Analytics Dashboard Data
 * Clearly separates Meta-reported metrics (spend, impressions, clicks) from CRM-calculated metrics (converted leads, pipeline value, CPL)
 */
export const getMetaAnalytics = async (req: Request, res: Response): Promise<void> => {
  const msgField = "Get Meta Analytics";

  try {
    const tenantId = (req.user as any)?.tenantId || (req as any).tenant?.id;
    if (!tenantId) {
      res.status(400).json({ success: false, message: "Tenant context required" });
      return;
    }

    const objectTenantId = new mongoose.Types.ObjectId(tenantId);

    // 1. Fetch CRM Leads generated by Meta
    const [crmMetaLeads, crmTotalCount] = await Promise.all([
      Lead.find({
        tenant_id: objectTenantId,
        $or: [
          { meta_lead_id: { $exists: true, $ne: "" } },
          { meta_source: { $regex: /meta|facebook|instagram/i } },
        ],
      }).lean(),
      Lead.countDocuments({ tenant_id: objectTenantId }),
    ]);

    // Calculate CRM pipeline metrics
    const totalLeadsFromMeta = crmMetaLeads.length;
    let convertedLeadsCount = 0;
    let totalRevenue = 0;

    crmMetaLeads.forEach((lead) => {
      const statusLower = (lead.status || "").toLowerCase();
      if (statusLower.includes("won") || statusLower.includes("closed") || statusLower.includes("converted") || statusLower.includes("customer")) {
        convertedLeadsCount++;
        totalRevenue += (lead as any).deal_value || (lead as any).revenue || 0;
      }
    });

    const conversionRate = totalLeadsFromMeta > 0 ? (convertedLeadsCount / totalLeadsFromMeta) * 100 : 0;

    // 2. Fetch Campaign Metrics from MetaCampaign collection
    const campaigns = await MetaCampaign.find({ tenant_id: objectTenantId }).lean();
    let totalSpend = 0;
    let metaReportedLeads = 0;

    campaigns.forEach((c) => {
      totalSpend += c.spend || 0;
      metaReportedLeads += c.leads_count || 0;
    });

    const costPerLead = totalLeadsFromMeta > 0 ? totalSpend / totalLeadsFromMeta : metaReportedLeads > 0 ? totalSpend / metaReportedLeads : 0;
    const roas = totalSpend > 0 ? totalRevenue / totalSpend : 0;

    // 3. Breakdown by Campaign
    const campaignBreakdown = campaigns.map((c) => {
      const crmLeadsForCampaign = crmMetaLeads.filter((l) => l.meta_campaign_id === c.meta_campaign_id).length;
      return {
        id: c._id,
        meta_campaign_id: c.meta_campaign_id,
        name: c.name,
        objective: c.objective,
        status: c.status,
        spend: c.spend || 0,
        meta_reported_leads: c.leads_count || 0,
        crm_leads: crmLeadsForCampaign,
        cpl: c.cpl || (crmLeadsForCampaign > 0 ? (c.spend || 0) / crmLeadsForCampaign : 0),
      };
    });

    // 4. Breakdown by Platform (Facebook vs Instagram)
    let facebookLeadsCount = 0;
    let instagramLeadsCount = 0;
    crmMetaLeads.forEach((l) => {
      const source = (l.meta_source || "").toLowerCase();
      if (source.includes("instagram") || source.includes("ig")) {
        instagramLeadsCount++;
      } else {
        facebookLeadsCount++;
      }
    });

    // 5. Breakdown by Lead Form
    const leadForms = await MetaLeadForm.find({ tenant_id: objectTenantId }).lean();
    const formBreakdown = leadForms.map((f) => {
      const leadsCount = crmMetaLeads.filter((l) => l.meta_form_id === f.meta_form_id).length;
      return {
        form_id: f.meta_form_id,
        form_name: f.meta_form_name,
        page_name: f.meta_page_name,
        is_enabled: f.is_enabled,
        total_leads: f.total_leads_received || leadsCount,
        crm_leads: leadsCount,
        last_received: f.last_lead_received_at,
      };
    });

    res.status(200).json({
      success: true,
      message: `${msgField} Success`,
      data: {
        summary: {
          total_spend: totalSpend,
          total_leads: totalLeadsFromMeta,
          meta_reported_leads: metaReportedLeads,
          cost_per_lead: costPerLead,
          conversions: convertedLeadsCount,
          conversion_rate: parseFloat(conversionRate.toFixed(2)),
          total_revenue: totalRevenue,
          roas: parseFloat(roas.toFixed(2)),
        },
        platform_breakdown: {
          facebook: facebookLeadsCount,
          instagram: instagramLeadsCount,
        },
        campaigns: campaignBreakdown,
        forms: formBreakdown,
      },
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`${msgField} Error:`, message);
    res.status(500).json({ success: false, error: message });
  }
};

export default getMetaAnalytics;
